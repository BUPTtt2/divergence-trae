function createLens(hexagramId, name, theme) {
  return Object.freeze({
    hexagramId,
    name,
    themes: Object.freeze([theme]),
    reviewQuestions: Object.freeze([
      `关于“${theme}”，哪项前提仍未由已有证据核验？`,
    ]),
    failureModes: Object.freeze([
      `若“${theme}”的关键条件失效，最先可观察到的失败模式是什么？`,
    ]),
    counterfactualPrompts: Object.freeze([
      `如果“${theme}”的反转变量取相反值，哪些现有主张需要重新核验？`,
    ]),
    exitConditions: Object.freeze([
      `围绕“${theme}”，哪项可观察条件可作为本轮审查的退出条件？`,
    ]),
    forbiddenUses: Object.freeze([
      '不得以 Lens 改写事实、风险、审批或用户决定。',
      '不得将文化意象表述为预测、命运或行动裁决。',
    ]),
  });
}

export const HEXAGRAM_LENSES = Object.freeze(
  HEXAGRAMS.map(([name, theme], index) => createLens(index + 1, name, theme)),
);

